// Operations → OpenAPI 3.1. GraphQL operations share one HTTP path, so each one is listed
// under the root `x-site2api-graphql` extension (OpenAPI cannot express them as separate paths).
import { parseJson, type Exchange } from "../capture/har.js";
import type { AuthHints } from "../normalize/auth.js";
import { graphqlCall } from "../normalize/graphql.js";
import { inferScalarSchema, inferSchema, type Schema } from "../normalize/schema.js";
import { singular } from "../normalize/template.js";
import { redactValue } from "../redact.js";
import type { Operation, OperationAuth } from "./operations.js";

export interface SpecOptions {
  site: string;
  examples?: boolean;
}

type Json = Record<string, unknown>;

const STATUS_TEXT: Record<number, string> = {
  200: "OK",
  201: "Created",
  202: "Accepted",
  204: "No Content",
  301: "Moved Permanently",
  302: "Found",
  304: "Not Modified",
  400: "Bad Request",
  401: "Unauthorized",
  403: "Forbidden",
  404: "Not Found",
  409: "Conflict",
  422: "Unprocessable Entity",
  429: "Too Many Requests",
  500: "Internal Server Error",
};

const VERSION_SEGMENT = /^v\d+(?:\.\d+)?$/i;
const NOISE_SEGMENTS = new Set(["api", "rest", "rpc", "internal", "public"]);

export function buildSpec(ops: Operation[], hints: AuthHints, options: SpecOptions): Json {
  const primaryOrigin = mostCommonOrigin(ops);
  const usedIds = new Set<string>();
  const paths: Record<string, Record<string, unknown>> = {};
  const graphqlOps: Json[] = [];

  for (const op of ops) {
    if (op.graphql) {
      graphqlOps.push(graphqlEntry(op, options, usedIds));
      ensureGraphqlPath(paths, op, primaryOrigin);
      continue;
    }
    const item = (paths[op.template] ??= {});
    if (op.origin !== primaryOrigin) item.servers = [{ url: op.origin }];
    item[op.method.toLowerCase()] = restOperation(op, options, usedIds);
  }

  const spec: Json = {
    openapi: "3.1.0",
    info: {
      title: `${options.site} (reverse-engineered)`,
      version: "0.0.0",
      description:
        "Generated by site2api from recorded traffic. Operation names and descriptions are heuristic until the Infer stage runs.",
    },
    servers: [{ url: primaryOrigin }],
    paths,
  };
  const schemes = securitySchemes(hints);
  if (Object.keys(schemes).length > 0) spec.components = { securitySchemes: schemes };
  if (graphqlOps.length > 0) spec["x-site2api-graphql"] = graphqlOps;
  return spec;
}

function restOperation(op: Operation, options: SpecOptions, usedIds: Set<string>): Json {
  const operationId = uniqueId(restOperationId(op), usedIds);
  const out: Json = { operationId, summary: humanize(operationId) };

  const parameters: Json[] = op.params.map((p) => ({
    name: p.name,
    in: "path",
    required: true,
    schema: pathParamSchema(p.kind, p.values),
  }));
  parameters.push(...queryParameters(op.exchanges, options));
  if (parameters.length > 0) out.parameters = parameters;

  const body = requestBody(op.exchanges, options);
  if (body) out.requestBody = body;

  out.responses = responses(op.exchanges, options);
  // An explicit empty list means "observed without credentials", which the generator needs to know.
  const security = securityRequirement(op.auth);
  out.security = security ? [security] : [];
  out["x-site2api"] = meta(op);
  return out;
}

function graphqlEntry(op: Operation, options: SpecOptions, usedIds: Set<string>): Json {
  const gql = op.graphql!;
  const variables = op.exchanges.map((ex) => graphqlCall(ex)?.variables).filter((v) => v !== undefined);
  const entry: Json = {
    operationId: uniqueId(`graphql_${snake(gql.operationName)}`, usedIds),
    operationName: gql.operationName,
    operationType: gql.operationType,
    endpoint: { method: op.method, url: op.origin + op.template },
    query: gql.query,
  };
  if (variables.length > 0) entry.variables = inferSchema(variables);
  entry.response = inferSchema(op.exchanges.map((ex) => parseJson(ex.responseBody)).filter((v) => v !== undefined));
  if (options.examples && variables[0]) entry.exampleVariables = redactValue(variables[0]);
  const security = securityRequirement(op.auth);
  if (security) entry.security = [security];
  entry["x-site2api"] = meta(op);
  return entry;
}

function ensureGraphqlPath(paths: Record<string, Record<string, unknown>>, op: Operation, primaryOrigin: string) {
  const item = (paths[op.template] ??= {});
  if (op.origin !== primaryOrigin) item.servers = [{ url: op.origin }];
  const method = op.method.toLowerCase();
  if (item[method]) return;
  item[method] = {
    operationId: `${snake(op.template) || "root"}_endpoint`,
    summary: "GraphQL endpoint",
    description: "GraphQL endpoint. Individual operations are listed under x-site2api-graphql.",
    ...(method === "post"
      ? {
          requestBody: {
            required: true,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    query: { type: "string" },
                    operationName: { type: "string" },
                    variables: { type: "object" },
                  },
                  required: ["query"],
                },
              },
            },
          },
        }
      : {}),
    security: securityRequirement(op.auth) ? [securityRequirement(op.auth)] : [],
    responses: {
      "200": {
        description: "OK",
        content: {
          "application/json": {
            schema: { type: "object", properties: { data: { type: ["object", "null"] }, errors: { type: "array" } } },
          },
        },
      },
    },
  };
}

function pathParamSchema(kind: string, values: string[]): Schema {
  if (kind === "integer") return { type: "integer" };
  if (kind === "uuid") return { type: "string", format: "uuid" };
  if (kind === "date") return { type: "string", format: "date" };
  return inferScalarSchema(values).type === "integer" ? { type: "integer" } : { type: "string" };
}

function queryParameters(exchanges: Exchange[], options: SpecOptions): Json[] {
  const values = new Map<string, string[]>();
  const seenIn = new Map<string, number>();
  for (const ex of exchanges) {
    const names = new Set<string>();
    for (const [name, value] of ex.url.searchParams) {
      values.set(name, [...(values.get(name) ?? []), value]);
      names.add(name);
    }
    for (const name of names) seenIn.set(name, (seenIn.get(name) ?? 0) + 1);
  }
  return [...values.keys()].sort().map((name) => {
    const param: Json = {
      name,
      in: "query",
      required: seenIn.get(name) === exchanges.length,
      schema: inferScalarSchema(values.get(name)!),
    };
    if (options.examples) param.example = redactValue(values.get(name)![0], name);
    return param;
  });
}

function requestBody(exchanges: Exchange[], options: SpecOptions): Json | undefined {
  const byMime = new Map<string, unknown[]>();
  let withBody = 0;
  for (const ex of exchanges) {
    if (!ex.requestBody) continue;
    withBody++;
    const mime = (ex.requestMime ?? "").split(";")[0]!.trim().toLowerCase();
    let value: unknown;
    if (mime === "application/x-www-form-urlencoded") value = Object.fromEntries(new URLSearchParams(ex.requestBody));
    else value = parseJson(ex.requestBody);
    if (value === undefined) continue;
    const key = mime === "application/x-www-form-urlencoded" ? mime : "application/json";
    byMime.set(key, [...(byMime.get(key) ?? []), value]);
  }
  if (byMime.size === 0) return undefined;
  const content: Json = {};
  for (const [mime, samples] of byMime) {
    const media: Json = { schema: inferSchema(samples) };
    if (options.examples) media.example = redactValue(samples[0]);
    content[mime] = media;
  }
  return { required: withBody === exchanges.length, content };
}

function responses(exchanges: Exchange[], options: SpecOptions): Json {
  const byStatus = new Map<number, unknown[]>();
  for (const ex of exchanges) {
    const samples = byStatus.get(ex.status) ?? [];
    const body = parseJson(ex.responseBody);
    if (body !== undefined) samples.push(body);
    byStatus.set(ex.status, samples);
  }
  const out: Json = {};
  for (const status of [...byStatus.keys()].sort((a, b) => a - b)) {
    const samples = byStatus.get(status)!;
    const response: Json = { description: STATUS_TEXT[status] ?? `HTTP ${status}` };
    if (samples.length > 0) {
      const media: Json = { schema: inferSchema(samples) };
      if (options.examples) media.example = redactValue(samples[0]);
      response.content = { "application/json": media };
    }
    out[String(status)] = response;
  }
  return out;
}

function securitySchemes(hints: AuthHints): Json {
  const schemes: Json = {};
  if (hints.bearer) schemes.bearerAuth = { type: "http", scheme: "bearer" };
  for (const name of hints.sessionCookies) schemes[schemeName("cookie", name)] = { type: "apiKey", in: "cookie", name };
  for (const name of [...hints.csrfHeaders, ...hints.apiKeyHeaders]) {
    schemes[schemeName("header", name)] = { type: "apiKey", in: "header", name };
  }
  return schemes;
}

function securityRequirement(auth: OperationAuth): Json | undefined {
  const req: Json = {};
  if (auth.bearer) req.bearerAuth = [];
  for (const c of auth.cookies) req[schemeName("cookie", c)] = [];
  for (const h of [...auth.csrfHeaders, ...auth.apiKeyHeaders]) req[schemeName("header", h)] = [];
  return Object.keys(req).length > 0 ? req : undefined;
}

function schemeName(kind: "cookie" | "header", name: string): string {
  return `${kind}_${name.replace(/[^A-Za-z0-9._-]/g, "_")}`;
}

function meta(op: Operation): Json {
  const out: Json = { samples: op.exchanges.length };
  if (op.auth.setsCookies.length > 0) out.setsCookies = op.auth.setsCookies;
  if (op.graphql ? op.graphql.operationType !== "query" : op.method !== "GET") out.writes = true;
  return out;
}

export function restOperationId(op: Pick<Operation, "method" | "template">): string {
  const segments = op.template.split("/").filter(Boolean);
  const endsWithParam = segments.at(-1)?.startsWith("{") ?? false;
  const literals = segments.filter((s) => !s.startsWith("{") && !VERSION_SEGMENT.test(s) && !NOISE_SEGMENTS.has(s));
  const resource = snake(literals.at(-1) ?? "root");
  const plural = /s$/.test(resource) && !/ss$/.test(resource);

  switch (op.method) {
    case "GET":
      return endsWithParam ? `get_${singular(resource)}` : plural ? `list_${resource}` : `get_${resource}`;
    case "POST":
      return plural && !endsWithParam ? `create_${singular(resource)}` : `post_${resource}`;
    case "PUT":
    case "PATCH":
      return `update_${singular(resource)}`;
    case "DELETE":
      return `delete_${singular(resource)}`;
    default:
      return `${op.method.toLowerCase()}_${resource}`;
  }
}

function humanize(operationId: string): string {
  const text = operationId.replace(/_/g, " ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}

function uniqueId(base: string, used: Set<string>): string {
  let id = base;
  for (let n = 2; used.has(id); n++) id = `${base}_${n}`;
  used.add(id);
  return id;
}

function snake(text: string): string {
  return text
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .toLowerCase();
}

function mostCommonOrigin(ops: Operation[]): string {
  const counts = new Map<string, number>();
  for (const op of ops) counts.set(op.origin, (counts.get(op.origin) ?? 0) + op.exchanges.length);
  return [...counts].sort((a, b) => b[1] - a[1])[0]?.[0] ?? "http://localhost";
}
